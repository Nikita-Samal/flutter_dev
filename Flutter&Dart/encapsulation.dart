-Encapsulation is a fundamental concept in object-oriented programming (OOP) that involves bundling the data (attributes) and methods (functions) that operate on the data within a single unit, typically a class.
-It helps in hiding the internal details of an object and exposing only the necessary information to the outside world.
-In Dart, encapsulation is achieved by using access modifiers like private (_) and public (no prefix).
-Private members can only be accessed within the same class.
-Public members can be accessed from anywhere.
-It provides data protection and supports the principle of information hiding, allowing you to control how the data is accessed and modified.


